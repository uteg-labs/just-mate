def _make_cell(cell_type: str, source: list[str], idx: int) -> dict:
    if cell_type == "markdown":
        return {
            "cell_type": "markdown", "metadata": {},
            "source": [s + "\n" for s in source[:-1]] + [source[-1]],
            "id": f"md-{idx}",
        }
    if cell_type == "code":
        return {
            "cell_type": "code", "execution_count": None, "metadata": {},
            "outputs": [],
            "source": [s + "\n" for s in source[:-1]] + [source[-1]],
            "id": f"code-{idx}",
        }
    raise ValueError(cell_type)


def main() -> None:
    cells = [_make_cell(c, s, i) for i, (c, s) in enumerate(CELLS)]
    nb = {
        "cells": cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3 (.venv)",
                "language": "python", "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.11", "file_extension": ".py"},
        },
        "nbformat": 4, "nbformat_minor": 5,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(nb, ensure_ascii=False, indent=1))
    print(f"wrote {OUT}  ({len(cells)} cells)")


if __name__ == "__main__":
    main()